import { chromium } from '@playwright/test'
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' })
const page = await context.newPage()
const errors = []
page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text().slice(0, 200)) })
page.on('pageerror', err => errors.push('pageerror: ' + err.message))
await page.addInitScript(() => {
  sessionStorage.setItem('loggedInUser', 'ausbitbank')
  sessionStorage.setItem('loginType', 'keychain')
})
await page.goto('https://banksia.io/settings/skin', { waitUntil: 'domcontentloaded', timeout: 60000 })
await page.waitForSelector('.studio-grid', { timeout: 60000 })
const select = page.locator('.q-select').filter({ has: page.locator('.q-field__label:text-is("Show up to 6 earned badges")') }).first()
await page.waitForTimeout(35000)
await select.click()
await page.waitForTimeout(700)
let texts = await page.getByRole('option').allInnerTexts()
console.log('options', texts.length)
console.log('has peakd?', texts.some(t => /PeakD/.test(t)), texts.slice(-12))
// select the first option
await page.getByRole('option').first().click()
await page.waitForTimeout(500)
console.log('chips after add', await select.locator('.q-chip').count())
console.log('preview badges', await page.locator('.studio-preview .skin-badge-chip').count())
// remove via chip close button
const chip = select.locator('.q-chip').first()
const remove = chip.locator('.q-chip__icon--remove, .q-icon').last()
await remove.click()
await page.waitForTimeout(500)
console.log('chips after delete', await select.locator('.q-chip').count())
await select.click()
await page.waitForTimeout(700)
texts = await page.getByRole('option').allInnerTexts()
console.log('options after delete', texts.length)
console.log('errors', errors.slice(0, 5))
await browser.close()
